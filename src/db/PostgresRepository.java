    public ArrayList<Room> loadRooms() {
        ArrayList<Room> list = new ArrayList<>();
        if (!isConnected()) return list;

        Map<String, Room> roomMap = new HashMap<>();
        String sqlRooms = "SELECT room_number, floor, block, capacity FROM rooms ORDER BY room_number ASC";
        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(sqlRooms);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                String roomNo = rs.getString("room_number");
                Room r = new Room(roomNo, rs.getInt("floor"), rs.getString("block"), rs.getInt("capacity"));
                // Clear default beds generated by constructor to accurately reflect DB state
                r.getBeds().clear();
                roomMap.put(roomNo, r);
                list.add(r);
            }
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error loading rooms: " + e.getMessage());
            return list;
        }

        String sqlBeds = "SELECT bed_code, room_number, is_occupied, allocated_student_id FROM beds ORDER BY bed_code ASC";
        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(sqlBeds);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                String roomNo = rs.getString("room_number");
                Room r = roomMap.get(roomNo);
                if (r != null) {
                    Bed bed = new Bed(rs.getString("bed_code"));
                    bed.setOccupied(rs.getBoolean("is_occupied"));
                    bed.setAllocatedStudentId(rs.getString("allocated_student_id"));
                    r.getBeds().add(bed);
                }
            }
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error loading beds: " + e.getMessage());
        }

        return list;
    }

    public ArrayList<User> loadUsers(Map<String, MessPlan> messPlanMap) {
        ArrayList<User> list = new ArrayList<>();
        if (!isConnected()) return list;

        // 1. Load Admin and Staff
        String sqlUsers = "SELECT id, name, email, password, role, department, role_designation, assigned_block FROM users";
        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(sqlUsers);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                String role = rs.getString("role");
                String id = rs.getString("id");
                String name = rs.getString("name");
                String email = rs.getString("email");
                String pass = rs.getString("password");

                if ("ADMIN".equalsIgnoreCase(role)) {
                    list.add(new Admin(id, name, email, pass, rs.getString("department")));
                } else if ("STAFF".equalsIgnoreCase(role)) {
                    list.add(new Staff(id, name, email, pass, rs.getString("role_designation"), rs.getString("assigned_block")));
                }
            }
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error loading users: " + e.getMessage());
        }

        // 2. Load Students with complete nested profile & state
        String sqlStudents = "SELECT u.id, u.name, u.email, u.password, " +
                "s.student_id, s.full_name, s.phone, s.gender, s.branch, s.year, s.address, " +
                "s.guardian_name, s.guardian_phone, s.document_type, s.document_number, " +
                "s.document_submitted, s.undertaking_accepted, s.payment_id, s.payment_amount, " +
                "s.payment_status, s.payment_date, s.transaction_ref, s.personal_details_completed, " +
                "s.documents_submitted_flag, s.undertaking_accepted_flag, s.fee_paid_flag, " +
                "s.admin_verified, s.room_bed_selected, s.mess_selected, s.laundry_activated, " +
                "s.pass_generated, s.allocated_room, s.allocated_bed, s.mess_plan_id, " +
                "s.laundry_total_cycles, s.laundry_used_cycles, s.laundry_status, " +
                "s.wifi_username, s.wifi_allocated_gb, s.wifi_used_gb, " +
                "s.pass_id, s.pass_issue_date, s.pass_verification_code, s.pass_status " +
                "FROM students s JOIN users u ON s.id = u.id";

        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(sqlStudents);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                Student s = new Student(
                        rs.getString("id"),
                        rs.getString("name"),
                        rs.getString("email"),
                        rs.getString("password"),
                        rs.getString("student_id")
                );

                // Personal Details
                PersonalDetails pd = s.getPersonalDetails();
                pd.setFullName(rs.getString("full_name"));
                pd.setPhone(rs.getString("phone"));
                pd.setGender(rs.getString("gender"));
                pd.setBranch(rs.getString("branch"));
                pd.setYear(rs.getInt("year"));
                pd.setAddress(rs.getString("address"));
                pd.setGuardianName(rs.getString("guardian_name"));
                pd.setGuardianPhone(rs.getString("guardian_phone"));

                // Document
                Document doc = s.getDocument();
                doc.setDocumentNumber(rs.getString("document_number") != null ? rs.getString("document_number") : "");
                doc.setSubmitted(rs.getBoolean("document_submitted"));
                doc.setUndertakingAccepted(rs.getBoolean("undertaking_accepted"));

                // Payment
                Payment payment = s.getPayment();
                payment.setPaymentId(rs.getString("payment_id") != null ? rs.getString("payment_id") : "PAY-PENDING");
                payment.setAmount(rs.getDouble("payment_amount"));
                payment.setStatus(rs.getString("payment_status") != null ? rs.getString("payment_status") : "PENDING");
                payment.setPaymentDate(rs.getString("payment_date") != null ? rs.getString("payment_date") : "N/A");
                payment.setTransactionRef(rs.getString("transaction_ref") != null ? rs.getString("transaction_ref") : "N/A");

                // OnboardingApplication
                OnboardingApplication app = s.getOnboardingApp();
                app.setPersonalDetailsCompleted(rs.getBoolean("personal_details_completed"));
                app.setDocumentsSubmitted(rs.getBoolean("documents_submitted_flag"));
                app.setUndertakingAccepted(rs.getBoolean("undertaking_accepted_flag"));
                app.setFeePaid(rs.getBoolean("fee_paid_flag"));
                app.setAdminVerified(rs.getBoolean("admin_verified"));
                app.setRoomBedSelected(rs.getBoolean("room_bed_selected"));
                app.setMessSelected(rs.getBoolean("mess_selected"));
                app.setLaundryPlanActivated(rs.getBoolean("laundry_activated"));
                app.setHostelPassGenerated(rs.getBoolean("pass_generated"));

                // Allocations
                s.setAllocatedRoom(rs.getString("allocated_room"));
                s.setAllocatedBed(rs.getString("allocated_bed"));

                // Mess Plan
                String planId = rs.getString("mess_plan_id");
                if (planId != null && messPlanMap.containsKey(planId)) {
                    s.setMessPlan(messPlanMap.get(planId));
                }

                // Laundry Plan
                LaundryPlan lp = s.getLaundryPlan();
                lp.setTotalCycles(rs.getInt("laundry_total_cycles"));
                lp.setUsedCycles(rs.getInt("laundry_used_cycles"));
                lp.setStatus(rs.getString("laundry_status") != null ? rs.getString("laundry_status") : "INACTIVE");

                // Wi-Fi
                WiFiAccount wifi = s.getWifiAccount();
                wifi.setAllocatedGB(rs.getDouble("wifi_allocated_gb"));
                wifi.setUsedGB(rs.getDouble("wifi_used_gb"));

                // Hostel Pass
                String passId = rs.getString("pass_id");
                if (passId != null && !passId.isEmpty()) {
                    HostelPass pass = new HostelPass(
                            passId,
                            s.getStudentId(),
                            s.getName(),
                            s.getAllocatedRoom(),
                            s.getAllocatedBed(),
                            s.getMessPlan() != null ? s.getMessPlan().getPlanName() : "Standard",
                            rs.getString("pass_issue_date")
                    );
                    if (rs.getString("pass_status") != null) {
                        pass.setStatus(rs.getString("pass_status"));
                    }
                    s.setHostelPass(pass);
                }

                list.add(s);
            }
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error loading students: " + e.getMessage());
        }

        return list;
    }

