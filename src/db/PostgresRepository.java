    public void saveStudent(Student s) {
        if (!isConnected()) return;

        // 1. Ensure user row exists
        String upsertUser = "INSERT INTO users (id, name, email, password, role) " +
                "VALUES (?, ?, ?, ?, 'STUDENT') " +
                "ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, email = EXCLUDED.email";
        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(upsertUser)) {
            ps.setString(1, s.getId());
            ps.setString(2, s.getName());
            ps.setString(3, s.getEmail());
            ps.setString(4, s.getPassword());
            ps.executeUpdate();
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error upserting user: " + e.getMessage());
        }

        // 2. Upsert student details
        String upsertStudent = "INSERT INTO students (" +
                "id, student_id, full_name, phone, gender, branch, year, address, " +
                "guardian_name, guardian_phone, document_type, document_number, " +
                "document_submitted, undertaking_accepted, payment_id, payment_amount, " +
                "payment_status, payment_date, transaction_ref, personal_details_completed, " +
                "documents_submitted_flag, undertaking_accepted_flag, fee_paid_flag, " +
                "admin_verified, room_bed_selected, mess_selected, laundry_activated, " +
                "pass_generated, allocated_room, allocated_bed, mess_plan_id, " +
                "laundry_total_cycles, laundry_used_cycles, laundry_status, " +
                "wifi_username, wifi_allocated_gb, wifi_used_gb, " +
                "pass_id, pass_issue_date, pass_verification_code, pass_status" +
                ") VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) " +
                "ON CONFLICT (id) DO UPDATE SET " +
                "full_name = EXCLUDED.full_name, phone = EXCLUDED.phone, gender = EXCLUDED.gender, " +
                "branch = EXCLUDED.branch, year = EXCLUDED.year, address = EXCLUDED.address, " +
                "guardian_name = EXCLUDED.guardian_name, guardian_phone = EXCLUDED.guardian_phone, " +
                "document_number = EXCLUDED.document_number, document_submitted = EXCLUDED.document_submitted, " +
                "undertaking_accepted = EXCLUDED.undertaking_accepted, payment_id = EXCLUDED.payment_id, " +
                "payment_amount = EXCLUDED.payment_amount, payment_status = EXCLUDED.payment_status, " +
                "payment_date = EXCLUDED.payment_date, transaction_ref = EXCLUDED.transaction_ref, " +
                "personal_details_completed = EXCLUDED.personal_details_completed, " +
                "documents_submitted_flag = EXCLUDED.documents_submitted_flag, " +
                "undertaking_accepted_flag = EXCLUDED.undertaking_accepted_flag, " +
                "fee_paid_flag = EXCLUDED.fee_paid_flag, admin_verified = EXCLUDED.admin_verified, " +
                "room_bed_selected = EXCLUDED.room_bed_selected, mess_selected = EXCLUDED.mess_selected, " +
                "laundry_activated = EXCLUDED.laundry_activated, pass_generated = EXCLUDED.pass_generated, " +
                "allocated_room = EXCLUDED.allocated_room, allocated_bed = EXCLUDED.allocated_bed, " +
                "mess_plan_id = EXCLUDED.mess_plan_id, laundry_total_cycles = EXCLUDED.laundry_total_cycles, " +
                "laundry_used_cycles = EXCLUDED.laundry_used_cycles, laundry_status = EXCLUDED.laundry_status, " +
                "wifi_used_gb = EXCLUDED.wifi_used_gb, pass_id = EXCLUDED.pass_id, " +
                "pass_issue_date = EXCLUDED.pass_issue_date, pass_verification_code = EXCLUDED.pass_verification_code, " +
                "pass_status = EXCLUDED.pass_status";

        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(upsertStudent)) {
            ps.setString(1, s.getId());
            ps.setString(2, s.getStudentId());

            PersonalDetails pd = s.getPersonalDetails();
            ps.setString(3, pd != null ? pd.getFullName() : s.getName());
            ps.setString(4, pd != null ? pd.getPhone() : null);
            ps.setString(5, pd != null ? pd.getGender() : null);
            ps.setString(6, pd != null ? pd.getBranch() : null);
            ps.setInt(7, pd != null ? pd.getYear() : 1);
            ps.setString(8, pd != null ? pd.getAddress() : null);
            ps.setString(9, pd != null ? pd.getGuardianName() : null);
            ps.setString(10, pd != null ? pd.getGuardianPhone() : null);

            Document doc = s.getDocument();
            ps.setString(11, doc != null ? doc.getDocumentType() : "Aadhaar Card");
            ps.setString(12, doc != null ? doc.getDocumentNumber() : null);
            ps.setBoolean(13, doc != null && doc.isSubmitted());
            ps.setBoolean(14, doc != null && doc.isUndertakingAccepted());

            Payment payment = s.getPayment();
            ps.setString(15, payment != null ? payment.getPaymentId() : null);
            ps.setDouble(16, payment != null ? payment.getAmount() : 85000.0);
            ps.setString(17, payment != null ? payment.getStatus() : "PENDING");
            ps.setString(18, payment != null ? payment.getPaymentDate() : null);
            ps.setString(19, payment != null ? payment.getTransactionRef() : null);

            OnboardingApplication app = s.getOnboardingApp();
            ps.setBoolean(20, app != null && app.isPersonalDetailsCompleted());
            ps.setBoolean(21, app != null && app.isDocumentsSubmitted());
            ps.setBoolean(22, app != null && app.isUndertakingAccepted());
            ps.setBoolean(23, app != null && app.isFeePaid());
            ps.setBoolean(24, app != null && app.isAdminVerified());
            ps.setBoolean(25, app != null && app.isRoomBedSelected());
            ps.setBoolean(26, app != null && app.isMessSelected());
            ps.setBoolean(27, app != null && app.isLaundryPlanActivated());
            ps.setBoolean(28, app != null && app.isHostelPassGenerated());

            ps.setString(29, s.getAllocatedRoom());
            ps.setString(30, s.getAllocatedBed());
            ps.setString(31, s.getMessPlan() != null ? s.getMessPlan().getPlanId() : null);

            LaundryPlan lp = s.getLaundryPlan();
            ps.setInt(32, lp != null ? lp.getTotalCycles() : 30);
            ps.setInt(33, lp != null ? lp.getUsedCycles() : 0);
            ps.setString(34, lp != null ? lp.getStatus() : "INACTIVE");

            WiFiAccount wifi = s.getWifiAccount();
            ps.setString(35, wifi != null ? wifi.getUsername() : s.getStudentId());
            ps.setDouble(36, wifi != null ? wifi.getAllocatedGB() : 300.0);
            ps.setDouble(37, wifi != null ? wifi.getUsedGB() : 0.0);

            HostelPass pass = s.getHostelPass();
            ps.setString(38, pass != null ? pass.getPassId() : null);
            ps.setString(39, pass != null ? pass.getIssueDate() : null);
            ps.setString(40, pass != null ? String.valueOf(pass.getPassId().hashCode()) : null);
            ps.setString(41, pass != null ? pass.getStatus() : "ACTIVE");

            ps.executeUpdate();
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error upserting student: " + e.getMessage());
        }
    }

    public void saveBedAllocation(String roomNumber, String bedCode, boolean occupied, String studentId) {
        if (!isConnected()) return;

        String sqlBed = "UPDATE beds SET is_occupied = ?, allocated_student_id = ? " +
                "WHERE room_number = ? AND (bed_code = ? OR bed_code = ?)";
        try (Connection conn = DatabaseConfig.getConnection();
             PreparedStatement ps = conn.prepareStatement(sqlBed)) {
            ps.setBoolean(1, occupied);
            ps.setString(2, studentId);
            ps.setString(3, roomNumber);
            ps.setString(4, bedCode);
            // Handle both "Bed A" and "101-A" variations
            ps.setString(5, roomNumber + "-" + (bedCode != null ? bedCode.replace("Bed ", "").trim() : ""));
            ps.executeUpdate();
        } catch (SQLException e) {
            System.err.println("[PostgreSQL] Error updating bed allocation: " + e.getMessage());
        }

        if (studentId != null) {
            String sqlStudent = "UPDATE students SET allocated_room = ?, allocated_bed = ?, room_bed_selected = ? " +
                    "WHERE student_id = ? OR id = ?";
            try (Connection conn = DatabaseConfig.getConnection();
                 PreparedStatement ps = conn.prepareStatement(sqlStudent)) {
                ps.setString(1, occupied ? roomNumber : null);
                ps.setString(2, occupied ? bedCode : null);
                ps.setBoolean(3, occupied);
                ps.setString(4, studentId);
                ps.setString(5, studentId);
                ps.executeUpdate();
            } catch (SQLException e) {
                System.err.println("[PostgreSQL] Error updating student room allocation: " + e.getMessage());
            }
        }
    }

